import { afterEach, expect, it, vi } from 'vitest'
afterEach(() => { vi.restoreAllMocks(); localStorage.clear(); vi.resetModules() })
it('uses saved language before browser preference, validates persisted values and falls back without storage', async () => {
  localStorage.setItem('bui-locale', 'zh-CN')
  vi.resetModules()
  expect((await import('@/lib/i18n')).locale.value).toBe('zh-CN')
  localStorage.setItem('bui-locale', 'invalid')
  vi.spyOn(navigator, 'language', 'get').mockReturnValue('zh-CN')
  vi.resetModules()
  expect((await import('@/lib/i18n')).locale.value).toBe('zh-CN')
  localStorage.setItem('bui-locale', 'en')
  vi.resetModules()
  expect((await import('@/lib/i18n')).locale.value).toBe('en')
  vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('blocked') })
  vi.resetModules()
  expect((await import('@/lib/i18n')).locale.value).toBe('zh-CN')
})

it('updates document language, title and description on navigation and switching', async () => {
  const { nextTick } = await import('vue')
  const { setLocale } = await import('@/lib/i18n')
  const { router } = await import('@/router')
  vi.spyOn(window, 'scrollTo').mockImplementation(() => {})
  document.head.innerHTML = '<meta name="description" content="">'
  setLocale('zh-CN')
  await router.push('/harness'); await nextTick()
  expect(document.documentElement.lang).toBe('zh-CN')
  expect(document.title).toContain('冰淇淋工作区演示')
  expect(document.querySelector('meta')?.getAttribute('content')).toContain('Vue 组件')
  setLocale('en'); await nextTick()
  expect(document.title).toContain('Ice Cream Harness')
  expect(document.documentElement.lang).toBe('en')
  await router.push('/missing'); await nextTick()
  expect(document.title).toBe('Page not found')
})
